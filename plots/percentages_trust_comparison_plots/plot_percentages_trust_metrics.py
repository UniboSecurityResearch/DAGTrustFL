#!/usr/bin/env python3
"""
Plotting script for DAGTrustFL percentages trust experiments analysis.
This script creates visualizations from the results of automated_test_percentages_trust.py
and compare_percentages_results_trust.py.

Based on plot_percentages_metrics.py but adapted for trust-specific analysis.
Reads from the CSV files generated by compare_percentages_results_trust.py.
"""

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np
from pathlib import Path
import warnings
warnings.filterwarnings('ignore')

# Set matplotlib font configuration like lambda_metrics
plt.rcParams.update({
    'font.family': ['Roboto', 'DejaVu Sans', 'Arial', 'sans-serif'],
    'font.size': 16,
    'axes.titlesize': 18,
    'axes.labelsize': 16,
    'xtick.labelsize': 16,
    'ytick.labelsize': 16,
    'legend.fontsize': 16,
    'figure.titlesize': 18,
    'text.usetex': False
})

# Set seaborn style
sns.set_style("whitegrid")
plt.style.use('seaborn-v0_8')

class PercentagesTrustPlotter:
    def __init__(self):
        self.base_dir = Path('/home/giac/DAGTrustFL/DAGTrustFL')
        self.comparison_dir = Path(__file__).parent  # Current directory (percentages_trust_comparison_plots)
        self.csv_dir = self.comparison_dir / 'csv_data'
        self.output_dir = self.comparison_dir / 'plots'
        
        # Create output directory
        self.output_dir.mkdir(exist_ok=True)
        
        # Color scheme consistent with other plots
        self.colors = {
            'primary': '#2E86AB',
            'secondary': '#A23B72', 
            'accent': '#F18F01',
            'success': '#C73E1D',
            'background': '#F8F9FA',
            'grid': '#E0E0E0',
            'malicious': '#d62728',
            'corrupted': '#ff7f0e',
            'total': '#2ca02c',
            'baseline': '#1f77b4'
        }

    def load_trust_data(self):
        """Load the trust experiment data from CSV files"""
        # Try to load the summary statistics file
        summary_file = self.csv_dir / 'percentages_trust_summary_statistics.csv'
        
        if not summary_file.exists():
            print(f"❌ Summary file not found: {summary_file}")
            print("Please run compare_percentages_results_trust.py first")
            return None
            
        try:
            df = pd.read_csv(summary_file)
            print(f"✓ Loaded trust summary data: {len(df)} experiments")
            print(f"Columns: {list(df.columns)}")
            return df
        except Exception as e:
            print(f"❌ Error loading trust summary data: {e}")
            return None

    def create_baseline_comparison_plot(self, df):
        """Create baseline vs threat scenarios comparison"""
        if df is None or len(df) == 0:
            print("❌ No data available for baseline comparison")
            return
            
        # Set up the plot
        fig, ((ax1, ax2), (ax3, ax4)) = plt.subplots(2, 2, figsize=(16, 12))
        
        # Separate baseline and threat scenarios
        baseline_df = df[df['is_baseline'] == True]
        threat_df = df[df['is_baseline'] == False]
        
        if len(baseline_df) == 0:
            print("❌ No baseline data (0% threats) found")
            return
            
        baseline_row = baseline_df.iloc[0]
        
        # Plot 1: FPR comparison
        if len(threat_df) > 0:
            threat_labels = [f"{row['malicious_perc']}%M,{row['corrupted_perc']}%C" 
                           for _, row in threat_df.iterrows()]
            threat_fpr = threat_df['fpr'].values
            baseline_fpr = baseline_row['fpr']
            
            bars1 = ax1.bar(range(len(threat_fpr)), threat_fpr, alpha=0.8, color=self.colors['malicious'], label='Threat scenarios')
            ax1.axhline(baseline_fpr, color=self.colors['baseline'], linestyle='--', linewidth=4, 
                       label=f'Baseline: {baseline_fpr:.1f}%', alpha=0.9)
            ax1.set_xlabel('Configuration')
            ax1.set_ylabel('False Positive Rate (%)')
            ax1.set_title('FPR: Threat Scenarios vs Baseline')
            ax1.set_xticks(range(len(threat_labels)))
            ax1.set_xticklabels(threat_labels, rotation=45)
            ax1.legend(fontsize=14)
            ax1.grid(True, alpha=0.3, linestyle='--')
        
        # Plot 2: TPR comparison
        if len(threat_df) > 0:
            threat_tpr = threat_df['tpr_malicious'].values
            baseline_tpr = baseline_row['tpr_malicious']
            
            bars2 = ax2.bar(range(len(threat_tpr)), threat_tpr, alpha=0.8, color=self.colors['success'], label='Threat scenarios')
            ax2.axhline(baseline_tpr, color=self.colors['baseline'], linestyle='--', linewidth=4,
                       label=f'Baseline: {baseline_tpr:.1f}%', alpha=0.9)
            ax2.set_xlabel('Configuration')
            ax2.set_ylabel('True Positive Rate (%)')
            ax2.set_title('TPR: Threat Scenarios vs Baseline')
            ax2.set_xticks(range(len(threat_labels)))
            ax2.set_xticklabels(threat_labels, rotation=45)
            ax2.legend(fontsize=14)
            ax2.grid(True, alpha=0.3, linestyle='--')
        
        # Plot 3: FNR comparison
        if len(threat_df) > 0:
            threat_fnr = threat_df['fnr_malicious'].values
            baseline_fnr = baseline_row['fnr_malicious']
            
            bars3 = ax3.bar(range(len(threat_fnr)), threat_fnr, alpha=0.8, color=self.colors['accent'], label='Threat scenarios')
            ax3.axhline(baseline_fnr, color=self.colors['baseline'], linestyle='--', linewidth=4,
                       label=f'Baseline: {baseline_fnr:.1f}%', alpha=0.9)
            ax3.set_xlabel('Configuration')
            ax3.set_ylabel('False Negative Rate (%)')
            ax3.set_title('FNR: Threat Scenarios vs Baseline')
            ax3.set_xticks(range(len(threat_labels)))
            ax3.set_xticklabels(threat_labels, rotation=45)
            ax3.legend(fontsize=14)
            ax3.grid(True, alpha=0.3, linestyle='--')
        
        # Plot 4: Accuracy comparison
        if len(threat_df) > 0:
            threat_acc = threat_df['accuracy'].values
            baseline_acc = baseline_row['accuracy']
            
            bars4 = ax4.bar(range(len(threat_acc)), threat_acc, alpha=0.8, color=self.colors['primary'], label='Threat scenarios')
            ax4.axhline(baseline_acc, color=self.colors['baseline'], linestyle='--', linewidth=4,
                       label=f'Baseline: {baseline_acc:.1f}%', alpha=0.9)
            ax4.set_xlabel('Configuration')
            ax4.set_ylabel('Accuracy (%)')
            ax4.set_title('Accuracy: Threat Scenarios vs Baseline')
            ax4.set_xticks(range(len(threat_labels)))
            ax4.set_xticklabels(threat_labels, rotation=45)
            ax4.legend(fontsize=14)
            ax4.grid(True, alpha=0.3, linestyle='--')
        
        plt.suptitle('Trust Performance: Baseline vs Threat Scenarios', fontsize=20, fontweight='bold')
        plt.tight_layout()
        
        # Save the plot
        plot_filename = self.output_dir / 'baseline_threat_comparison.png'
        plt.savefig(plot_filename, dpi=300, bbox_inches='tight', 
                   facecolor='white', edgecolor='none')
        
        print(f"✓ Baseline comparison plot saved: {plot_filename}")
        
        # Also save as PDF
        pdf_filename = self.output_dir / 'baseline_threat_comparison.pdf'
        plt.savefig(pdf_filename, bbox_inches='tight', 
                   facecolor='white', edgecolor='none')
        
        plt.show()
        plt.close()

    def create_trust_degradation_analysis(self, df):
        """Create trust degradation analysis plot"""
        if df is None or len(df) == 0:
            print("❌ No data available for trust degradation analysis")
            return
            
        # Set up the plot
        fig, ((ax1, ax2), (ax3, ax4)) = plt.subplots(2, 2, figsize=(16, 12))
        
        # Plot 1: Ranking vs Configuration
        df_sorted = df.sort_values('ranking')
        
        # Color code by baseline vs threats
        colors = [self.colors['baseline'] if row['is_baseline'] else self.colors['secondary'] 
                 for _, row in df_sorted.iterrows()]
        
        bars1 = ax1.bar(range(len(df_sorted)), df_sorted['composite_score'], 
                       color=colors, alpha=0.8)
        ax1.set_xlabel('Configuration (by rank)')
        ax1.set_ylabel('Composite Score')
        ax1.set_title('Trust Configuration Performance Ranking')
        ax1.grid(True, alpha=0.3, linestyle='--')
        
        # Add labels
        labels = [f"{row['malicious_perc']}%M,{row['corrupted_perc']}%C" 
                 for _, row in df_sorted.iterrows()]
        ax1.set_xticks(range(len(labels)))
        ax1.set_xticklabels(labels, rotation=45)
        
        # Plot 2: Total threat level impact
        if len(df[~df['is_baseline']]) > 0:
            threat_df = df[~df['is_baseline']].copy()
            threat_df = threat_df.sort_values('total_perc')
            
            ax2.plot(threat_df['total_perc'], threat_df['composite_score'], 'o-', 
                    linewidth=4, markersize=14, color=self.colors['primary'], alpha=0.9)
            
            # Add baseline reference
            baseline_score = df[df['is_baseline']]['composite_score'].iloc[0] if len(df[df['is_baseline']]) > 0 else 0
            ax2.axhline(baseline_score, color=self.colors['baseline'], linestyle='--', 
                       linewidth=4, label=f'Baseline: {baseline_score:.1f}', alpha=0.9)
            
            ax2.set_xlabel('Total Threat Percentage (%)')
            ax2.set_ylabel('Composite Score')
            ax2.set_title('Performance vs Total Threat Level')
            ax2.grid(True, alpha=0.3, linestyle='--')
            ax2.legend(fontsize=14)
        
        # Plot 3: Individual metrics by total threat
        if len(df[~df['is_baseline']]) > 0:
            threat_df = df[~df['is_baseline']].copy()
            threat_df = threat_df.sort_values('total_perc')
            
            ax3.plot(threat_df['total_perc'], threat_df['fpr'], 'o-', 
                    linewidth=3, markersize=10, label='FPR', alpha=0.8)
            ax3.plot(threat_df['total_perc'], threat_df['tpr_malicious'], 's-', 
                    linewidth=3, markersize=10, label='TPR', alpha=0.8)
            ax3.plot(threat_df['total_perc'], threat_df['fnr_malicious'], '^-', 
                    linewidth=3, markersize=10, label='FNR', alpha=0.8)
            
            ax3.set_xlabel('Total Threat Percentage (%)')
            ax3.set_ylabel('Rate (%)')
            ax3.set_title('Detection Metrics vs Threat Level')
            ax3.legend(fontsize=14)
            ax3.grid(True, alpha=0.3, linestyle='--')
        
        # Plot 4: Accuracy degradation
        if len(df[~df['is_baseline']]) > 0:
            threat_df = df[~df['is_baseline']].copy()
            threat_df = threat_df.sort_values('total_perc')
            
            baseline_acc = df[df['is_baseline']]['accuracy'].iloc[0] if len(df[df['is_baseline']]) > 0 else 100
            accuracy_degradation = baseline_acc - threat_df['accuracy']
            
            bars4 = ax4.bar(range(len(threat_df)), accuracy_degradation, 
                           color=self.colors['malicious'], alpha=0.8)
            ax4.set_xlabel('Configuration')
            ax4.set_ylabel('Accuracy Loss from Baseline (%)')
            ax4.set_title('Trust Degradation: Accuracy Loss')
            ax4.grid(True, alpha=0.3, linestyle='--')
            
            threat_labels = [f"{row['total_perc']}%" for _, row in threat_df.iterrows()]
            ax4.set_xticks(range(len(threat_labels)))
            ax4.set_xticklabels(threat_labels)
        
        plt.suptitle('Trust System Degradation Analysis', fontsize=20, fontweight='bold')
        plt.tight_layout()
        
        # Save the plot
        plot_filename = self.output_dir / 'trust_degradation_analysis.png'
        plt.savefig(plot_filename, dpi=300, bbox_inches='tight', 
                   facecolor='white', edgecolor='none')
        
        print(f"✓ Trust degradation analysis saved: {plot_filename}")
        
        # Also save as PDF
        pdf_filename = self.output_dir / 'trust_degradation_analysis.pdf'
        plt.savefig(pdf_filename, bbox_inches='tight', 
                   facecolor='white', edgecolor='none')
        
        plt.show()
        plt.close()

    def create_trust_summary_table(self, df):
        """Create a summary table of all trust metrics"""
        if df is None or len(df) == 0:
            print("❌ No data available for summary table")
            return
            
        # Create summary plot
        fig, ax = plt.subplots(figsize=(16, 10))
        ax.axis('tight')
        ax.axis('off')
        
        # Prepare data for table
        df_sorted = df.sort_values('ranking')
        table_data = []
        
        for _, row in df_sorted.iterrows():
            status = "BASELINE" if row['is_baseline'] else "THREAT"
            table_data.append([
                f"{int(row['ranking'])}",
                f"{int(row['malicious_perc'])}%",
                f"{int(row['corrupted_perc'])}%", 
                f"{int(row['total_perc'])}%",
                f"{row['fpr']:.1f}%",
                f"{row['tpr_malicious']:.1f}%",
                f"{row['fnr_malicious']:.1f}%",
                f"{row['accuracy']:.1f}%",
                f"{row['composite_score']:.1f}",
                status
            ])
        
        # Create table
        table = ax.table(cellText=table_data,
                        colLabels=['Rank', 'Mal%', 'Cor%', 'Tot%', 'FPR', 'TPR', 'FNR', 'Acc', 'Score', 'Type'],
                        cellLoc='center',
                        loc='center',
                        bbox=[0, 0, 1, 1])
        
        # Style the table
        table.auto_set_font_size(False)
        table.set_fontsize(12)
        table.scale(1.2, 2)
        
        # Header styling
        for i in range(len(table_data[0])):
            table[(0, i)].set_facecolor(self.colors['primary'])
            table[(0, i)].set_text_props(weight='bold', color='white')
        
        # Data row styling
        for i in range(1, len(table_data) + 1):
            for j in range(len(table_data[0])):
                # Color baseline rows differently
                row_data = df_sorted.iloc[i-1]
                if row_data['is_baseline']:
                    table[(i, j)].set_facecolor(self.colors['background'])
                else:
                    if i % 2 == 0:
                        table[(i, j)].set_facecolor('#F5F5F5')
                    else:
                        table[(i, j)].set_facecolor('white')
        
        plt.title('DAGTrustFL Trust Analysis - Complete Summary', 
                 fontsize=20, fontweight='bold', pad=20)
        
        plt.tight_layout()
        
        # Save the plot
        plot_filename = self.output_dir / 'trust_summary_table.png'
        plt.savefig(plot_filename, dpi=300, bbox_inches='tight', 
                   facecolor='white', edgecolor='none')
        
        print(f"✓ Trust summary table saved: {plot_filename}")
        
        # Also save as PDF
        pdf_filename = self.output_dir / 'trust_summary_table.pdf'
        plt.savefig(pdf_filename, bbox_inches='tight', 
                   facecolor='white', edgecolor='none')
        
        plt.show()
        plt.close()

    def run_all_plots(self):
        """Run all plotting functions"""
        print("Starting DAGTrustFL Trust Percentages plotting...")
        print(f"Output directory: {self.output_dir}")
        
        # Load data
        df = self.load_trust_data()
        
        if df is None:
            print("❌ Cannot proceed without data")
            return
            
        print(f"\n📊 Creating plots for {len(df)} trust experiment combinations")
        
        # Generate all plots
        try:
            self.create_baseline_comparison_plot(df)
            self.create_trust_degradation_analysis(df)
            self.create_trust_summary_table(df)
            
            print(f"\n🎉 All trust plots generated successfully!")
            print(f"📁 Plots saved in: {self.output_dir}")
            
        except Exception as e:
            print(f"❌ Error during plotting: {e}")
            import traceback
            traceback.print_exc()

def main():
    """Main function"""
    plotter = PercentagesTrustPlotter()
    plotter.run_all_plots()

if __name__ == '__main__':
    main()
