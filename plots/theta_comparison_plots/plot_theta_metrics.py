#!/usr/bin/env python3
"""
Theta Metrics Plot for Theta Comparison
========================================

This script reads the CSV data generated by compare_theta_results.py and creates
a plot showing the FNR, FPR, and TPR metrics as Theta values evolve.

Theta Parameter: Confirmation Threshold
Values tested: [2, 3, 4, 5]

Colors:
- Dark Red: FNR (False Negative Rate)
- Dark Orange: FPR (False Positive Rate) 
- Dark Green: TPR (True Positive Rate)

Author: Giacomo Gori and GitHub Copilot Assistant
Date: August 30, 2025
"""

import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path
import sys

# Configure matplotlib with Roboto font and better looking plots
plt.style.use('seaborn-v0_8')
plt.rcParams['font.family'] = 'sans-serif'
plt.rcParams['font.sans-serif'] = ['Roboto', 'DejaVu Sans', 'Arial', 'sans-serif']
plt.rcParams['font.size'] = 16
plt.rcParams['axes.labelsize'] = 18
plt.rcParams['xtick.labelsize'] = 16
plt.rcParams['ytick.labelsize'] = 16
plt.rcParams['legend.fontsize'] = 16

def load_csv_data():
    """Load the CSV data from the csv_data directory."""
    csv_dir = Path("csv_data")
    
    if not csv_dir.exists():
        print("❌ CSV data directory not found! Please run compare_theta_results.py first.")
        return None
    
    # Load the theta comparison data file
    theta_file = csv_dir / "theta_comparison_data.csv"
    
    if not theta_file.exists():
        print("❌ Theta comparison data file not found! Please run compare_theta_results.py first.")
        return None
    
    try:
        df = pd.read_csv(theta_file)
        print(f"✅ Loaded data from {theta_file}")
        print(f"📊 Data shape: {df.shape}")
        print(f"📋 Theta values found: {sorted(df['theta'].unique())}")
        return df
    except Exception as e:
        print(f"❌ Error loading CSV data: {e}")
        return None

def create_theta_metrics_plot(df):
    """Create the plot with theta metrics."""
    
    # Set up the plot with wider dimensions
    fig, ax = plt.subplots(figsize=(8, 6))
    
    # Define colors
    colors = {
        'fnr': 'darkred',      # Dark Red for FNR
        'fpr': 'darkorange',   # Dark Orange for FPR
        'tpr': 'darkgreen'     # Dark Green for TPR
    }
    
    # Sort data by theta values
    df_sorted = df.sort_values('theta')
    theta_values = df_sorted['theta'].values
    
    # Plot the three metrics with larger markers and lines
    ax.plot(theta_values, df_sorted['fnr_malicious'], 'o-', 
           linewidth=4, markersize=14, color=colors['fnr'], 
           label='FNR', alpha=0.9)
    
    ax.plot(theta_values, df_sorted['fpr'], 's-', 
           linewidth=4, markersize=14, color=colors['fpr'], 
           label='FPR', alpha=0.9)
    
    ax.plot(theta_values, df_sorted['tpr_malicious'], '^-', 
           linewidth=4, markersize=14, color=colors['tpr'], 
           label='TPR', alpha=0.9)
    
    # Customize the plot
    ax.set_xlabel('Theta Value (Θ)', fontsize=20, fontweight='bold')
    ax.set_ylabel('Rate (%)', fontsize=20, fontweight='bold')
    
    # Add grid
    ax.grid(True, alpha=0.3, linestyle='--')
    
    # Set y-axis limits
    ax.set_ylim(0, 100)
    
    # Set x-axis to show all theta values with larger ticks
    ax.set_xticks(theta_values)
    ax.tick_params(axis='both', which='major', labelsize=16)
    
    # Add value labels on points with larger font
    for i, theta_val in enumerate(theta_values):
        fnr_val = df_sorted['fnr_malicious'].iloc[i]
        fpr_val = df_sorted['fpr'].iloc[i]
        tpr_val = df_sorted['tpr_malicious'].iloc[i]
        
        # FNR labels
        ax.annotate(f'{fnr_val:.1f}%', (theta_val, fnr_val), 
                   textcoords="offset points", xytext=(0, 12), 
                   ha='center', fontsize=12, color=colors['fnr'], fontweight='bold')
        
        # FPR labels
        ax.annotate(f'{fpr_val:.1f}%', (theta_val, fpr_val), 
                   textcoords="offset points", xytext=(0, 12), 
                   ha='center', fontsize=12, color=colors['fpr'], fontweight='bold')
        
        # TPR labels
        ax.annotate(f'{tpr_val:.1f}%', (theta_val, tpr_val), 
                   textcoords="offset points", xytext=(0, -18), 
                   ha='center', fontsize=12, color=colors['tpr'], fontweight='bold')
    
    # Add legend outside the plot (below)
    ax.legend(bbox_to_anchor=(0.5, -0.09), loc='upper center', 
             fontsize=18, framealpha=0.9, ncol=3)
    
    # Tight layout with extra space for legend
    plt.tight_layout()
    plt.subplots_adjust(bottom=0.15)  # Less space, bigger plot area
    
    return fig

def save_theta_data_csv(df):
    """Save the theta data to a CSV file."""
    csv_dir = Path("csv_data")
    output_file = csv_dir / "theta_metrics_plot_data.csv"
    
    try:
        # Sort by theta and select relevant columns
        df_sorted = df.sort_values('theta')
        plot_data = df_sorted[['theta', 'fnr_malicious', 'fpr', 'tpr_malicious', 'accuracy']].copy()
        plot_data.to_csv(output_file, index=False)
        print(f"💾 Theta plot data saved to: {output_file}")
    except Exception as e:
        print(f"⚠️ Error saving theta plot data: {e}")

def main():
    """Main function to create the theta metrics plot."""
    print("🚀 Starting Theta Metrics Plot Generation...")
    print("=" * 60)
    
    # Load CSV data
    df = load_csv_data()
    if df is None:
        return
    
    # Check if we have data
    if df.empty:
        print("⚠️ No theta data found in CSV file")
        return
    
    # Create the plot
    print("\n📈 Creating theta metrics plot...")
    fig = create_theta_metrics_plot(df)
    
    # Save the plot
    output_file = "theta_metrics_plot.png"
    fig.savefig(output_file, dpi=300, bbox_inches='tight', facecolor='white')
    print(f"📊 Plot saved as: {output_file}")
    
    # Also save as PDF
    output_pdf = "theta_metrics_plot.pdf"
    fig.savefig(output_pdf, bbox_inches='tight', facecolor='white')
    print(f"📑 Plot also saved as: {output_pdf}")
    
    # Save theta data to CSV
    save_theta_data_csv(df)
    
    # Show statistics
    print("\n📋 Summary Statistics:")
    print("-" * 40)
    df_sorted = df.sort_values('theta')
    for _, row in df_sorted.iterrows():
        theta_val = row['theta']
        print(f"Theta {theta_val}: FNR={row['fnr_malicious']:.1f}%, FPR={row['fpr']:.1f}%, TPR={row['tpr_malicious']:.1f}%")
    
    print("\n" + "=" * 60)
    print("🎉 THETA METRICS PLOT COMPLETED!")
    print(f"📊 Plot saved: {output_file}")
    print(f"📑 PDF saved: {output_pdf}")
    print("=" * 60)
    
    # Show additional information about theta parameter
    print("\n📖 THETA PARAMETER INFO:")
    print("-" * 40)
    print("Theta controls the confirmation threshold in the DAG:")
    print("• Θ = 2: Low threshold (easier confirmation)")
    print("• Θ = 3: Default threshold")
    print("• Θ = 4: High threshold (stricter confirmation)")
    print("• Θ = 5: Very high threshold (very strict)")
    print("Higher values require more cumulative weight for confirmation.")
    
    # Show the plot
    try:
        plt.show()
    except:
        print("💡 Plot display not available in this environment")

if __name__ == '__main__':
    main()
