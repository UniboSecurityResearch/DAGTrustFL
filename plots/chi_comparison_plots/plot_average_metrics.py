def load_csv_data():
    """Load the CSV data from the csv_data directory."""
    csv_dir = Path("csv_data")
    
    if not csv_dir.exists():
        print("❌ CSV data directory not found! Please run compare_chi_results.py first.")
        return None
    
    # Load the combined data file
    combined_file = csv_dir / "chi_comparison_all_data.csv"
    
    if not combined_file.exists():
        print("❌ Combined CSV data file not found! Please run compare_chi_results.py first.")
        return None
    
    try:
        df = pd.read_csv(combined_file)
        print(f"✅ Loaded data from {combined_file}")
        print(f"📊 Data shape: {df.shape}")
        print(f"📋 Configurations found: {df['configuration'].unique()}")
        return df
    except Exception as e:
        print(f"❌ Error loading CSV data: {e}")
        return None

def calculate_average_metrics(df):
    """Calculate average metrics between mal_20_cor_10 and mal_10_cor_20 configurations."""
    
    # Filter data for the two configurations we want to average
    config1_data = df[df['configuration'] == 'mal_20_cor_10'].copy()
    config2_data = df[df['configuration'] == 'mal_10_cor_20'].copy()
    
    if config1_data.empty:
        print("⚠️ No data found for mal_20_cor_10 configuration")
        return None
    
    if config2_data.empty:
        print("⚠️ No data found for mal_10_cor_20 configuration")
        return None
    
    # Get common chi values
    chi_values_1 = set(config1_data['chi'].values)
    chi_values_2 = set(config2_data['chi'].values)
    common_chi_values = sorted(chi_values_1 & chi_values_2)
    
    if not common_chi_values:
        print("⚠️ No common chi values found between configurations")
        return None
    
    print(f"📈 Common chi values: {common_chi_values}")
    
    # Calculate averages for each chi value
    averaged_data = []
    
    for chi in common_chi_values:
        # Get data for this chi value from both configurations
        data1 = config1_data[config1_data['chi'] == chi].iloc[0]
        data2 = config2_data[config2_data['chi'] == chi].iloc[0]
        
        # Calculate averages (midpoint between the two configurations)
        avg_fpr = (data1['fpr'] + data2['fpr']) / 2
        avg_tpr_malicious = (data1['tpr_malicious'] + data2['tpr_malicious']) / 2
        avg_fnr_malicious = (data1['fnr_malicious'] + data2['fnr_malicious']) / 2
        avg_accuracy = (data1['accuracy'] + data2['accuracy']) / 2
        
        averaged_data.append({
            'chi': chi,
            'avg_fpr': avg_fpr,
            'avg_tpr_malicious': avg_tpr_malicious,
            'avg_fnr_malicious': avg_fnr_malicious,
            'avg_accuracy': avg_accuracy,
            'config1_fpr': data1['fpr'],
            'config1_tpr': data1['tpr_malicious'],
            'config1_fnr': data1['fnr_malicious'],
            'config2_fpr': data2['fpr'],
            'config2_tpr': data2['tpr_malicious'],
            'config2_fnr': data2['fnr_malicious']
        })
        
        print(f"Chi {chi}: FPR={avg_fpr:.1f}%, DACC={avg_tpr_malicious:.1f}%, FNR={avg_fnr_malicious:.1f}%")
    
    return pd.DataFrame(averaged_data)

def create_average_metrics_plot(avg_df):
    """Create the combined plot with averaged metrics."""
    
    # Set up the plot with wider dimensions
    fig, ax = plt.subplots(figsize=(8, 6))
    
    # Define colors
    colors = {
        'fnr': 'darkred',      # Dark Red for FNR
        'fpr': 'darkorange',   # Dark Orange for FPR
        'tpr': 'darkgreen'     # Dark Green for DACC
    }
    
    chi_values = avg_df['chi'].values
    
    # Create custom labels for x-axis (chi values as fractions of K)
    chi_labels = []
    for chi in chi_values:
        if chi == 0:
            chi_labels.append('0')
        elif chi == 1:
            chi_labels.append('1')
        elif chi == 2:
            chi_labels.append('K/4')
        elif chi == 3:
            chi_labels.append('K/3')
        elif chi == 4:
            chi_labels.append('K/2')
        else:
            chi_labels.append(str(chi))  # fallback for other values
    
    # Plot the three metrics with larger markers and lines
    ax.plot(chi_values, avg_df['avg_fnr_malicious'], 'o-', 
           linewidth=4, markersize=12, color=colors['fnr'], 
           label='FNR', alpha=0.9)
    
    ax.plot(chi_values, avg_df['avg_fpr'], 's-', 
           linewidth=4, markersize=12, color=colors['fpr'], 
           label='FPR', alpha=0.9)
    
    ax.plot(chi_values, avg_df['avg_tpr_malicious'], '^-', 
           linewidth=4, markersize=12, color=colors['tpr'], 
           label='DACC', alpha=0.9)
    
    # Customize the plot - removed title
    ax.set_xlabel('Chi Value', fontsize=18, fontweight='bold')
    ax.set_ylabel('Rate (%)', fontsize=18, fontweight='bold')
    
    # Add grid
    ax.grid(True, alpha=0.3, linestyle='--')
    
    # Set y-axis limits
    ax.set_ylim(0, 100)
    
    # Set x-axis to show custom labels
    ax.set_xticks(chi_values)
    ax.set_xticklabels(chi_labels)
    ax.tick_params(axis='both', which='major', labelsize=16)
    
    # Add legend with larger font
    ax.legend(loc='upper right', fontsize=16, framealpha=0.9)
    
    # Add value labels on points with larger font
    for i, chi in enumerate(chi_values):
        fnr_val = avg_df['avg_fnr_malicious'].iloc[i]
        fpr_val = avg_df['avg_fpr'].iloc[i]
        tpr_val = avg_df['avg_tpr_malicious'].iloc[i]
        
        # FNR labels
        ax.annotate(f'{fnr_val:.1f}%', (chi, fnr_val), 
                   textcoords="offset points", xytext=(0, 12), 
                   ha='center', fontsize=12, color=colors['fnr'], fontweight='bold')
        
        # FPR labels
        ax.annotate(f'{fpr_val:.1f}%', (chi, fpr_val), 
                   textcoords="offset points", xytext=(0, 12), 
                   ha='center', fontsize=12, color=colors['fpr'], fontweight='bold')
        
        # DACC labels
        ax.annotate(f'{tpr_val:.1f}%', (chi, tpr_val), 
                   textcoords="offset points", xytext=(0, -18), 
                   ha='center', fontsize=12, color=colors['tpr'], fontweight='bold')
    
    # Add legend outside the plot (below)
    ax.legend(bbox_to_anchor=(0.5, -0.15), loc='upper center', 
             fontsize=16, framealpha=0.9, ncol=3)
    
    # Tight layout with extra space for legend
    plt.tight_layout()
    plt.subplots_adjust(bottom=0.2)  # Make room for legend below
    
    return fig

def save_averaged_data_csv(avg_df):
    """Save the averaged data to a CSV file."""
    csv_dir = Path("csv_data")
    output_file = csv_dir / "chi_averaged_metrics.csv"
    
    try:
        avg_df.to_csv(output_file, index=False)
        print(f"💾 Averaged data saved to: {output_file}")
    except Exception as e:
        print(f"⚠️ Error saving averaged data: {e}")

def main():
    """Main function to create the average metrics plot."""
    print("🚀 Starting Average Metrics Plot Generation...")
    print("=" * 60)
    
    # Load CSV data
    df = load_csv_data()
    if df is None:
        return
    
    # Calculate average metrics
    print("\n📊 Calculating average metrics between configurations...")
    avg_df = calculate_average_metrics(df)
    if avg_df is None:
        return
    
    # Create the plot
    print("\n📈 Creating average metrics plot...")
    fig = create_average_metrics_plot(avg_df)
    
    # Save the plot
    output_file = "chi_average_metrics_plot.png"
    fig.savefig(output_file, dpi=300, bbox_inches='tight', facecolor='white')
    print(f"📊 Plot saved as: {output_file}")
    
    # Also save as PDF
    output_pdf = "chi_average_metrics_plot.pdf"
    fig.savefig(output_pdf, bbox_inches='tight', facecolor='white')
    print(f"📑 Plot also saved as: {output_pdf}")
    
    # Save averaged data to CSV
    save_averaged_data_csv(avg_df)
    
    # Show statistics
    print("\n📋 Summary Statistics:")
    print("-" * 40)
    for _, row in avg_df.iterrows():
        chi = row['chi']
        print(f"Chi {chi}: FNR={row['avg_fnr_malicious']:.1f}%, FPR={row['avg_fpr']:.1f}%, DACC={row['avg_tpr_malicious']:.1f}%")
    
    print("\n" + "=" * 60)
    print("🎉 AVERAGE METRICS PLOT COMPLETED!")
    print(f"📊 Plot saved: {output_file}")
    print(f"📑 PDF saved: {output_pdf}")
    print("=" * 60)
    
    # Show the plot
    try:
        plt.show()
    except:
        print("💡 Plot display not available in this environment")

if __name__ == '__main__':
    main()
