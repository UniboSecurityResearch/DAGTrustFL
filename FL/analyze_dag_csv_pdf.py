        # Similarity analysis
        if 'Similarity_Threshold' in self.df.columns:
            print(f"\n📐 SIMILARITY ANALYSIS:")
            initial_threshold = self.df['Similarity_Threshold'].iloc[0]
            final_threshold = self.df['Similarity_Threshold'].iloc[-1]
